/** The diagram strings per language, to be merged into `messages/data.ts` by integration. */
export const DIAGRAM_MESSAGES: { en: Record<DiagramMessageKey, string>; es: Record<DiagramMessageKey, string>; fr: Record<DiagramMessageKey, string>; de: Record<DiagramMessageKey, string> } = {
  en,
  es,
  fr,
  de,
};

/** Fallback translator over `DIAGRAM_MESSAGES` (English for unknown keys; `{var}` interpolation like `src/lib/i18n`). */
export function diagramTranslator(lang: DiagramLang): DiagramTranslator {
  const dict = DIAGRAM_MESSAGES[lang] as Record<string, string>;
  const base = DIAGRAM_MESSAGES.en as Record<string, string>;
  return (key, vars) => {
    const template = dict[key] ?? base[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (m, k: string) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
  };
}

// ---------------------------------------------------------------------------------------------
// Small helpers shared by the admin pages (the server-side labels in `src/lib/client.ts` stay in English).
// ---------------------------------------------------------------------------------------------
type T = (key: string, vars?: Vars) => string;

const camel = (s: string) => s.replace(/_([a-z])/g, (_m, c: string) => c.toUpperCase());
const STATUSES = ["draft", "in_progress", "under_review", "revision_requested", "approved", "submitted"];
const MODE_IDS = ["chat", "brainstorm", "outline", "critique", "grammar", "summarize", "explain", "citations", "gaps", "paraphrase_check", "copilot"];
const NOTICE_TYPES = ["bulk_paste", "ai_generation", "style_inconsistency", "rapid_typing", "external_source", "unattributed_ai", "policy_limit"];

/** Thesis status id → localised label (unknown ids are shown as stored). */
export function statusLabel(t: T, status: string): string {
  return STATUSES.indexOf(status) >= 0 ? t(`admin.status.${camel(status)}`) : status;
}
/** Assistant mode id → localised label. */
export function modeLabel(t: T, mode: string): string {
  return MODE_IDS.indexOf(mode) >= 0 ? t(`admin.mode.${camel(mode)}`) : mode.replace(/_/g, " ");
}
/** Notice type id → localised label. */
export function noticeTypeLabel(t: T, type: string): string {
  return NOTICE_TYPES.indexOf(type) >= 0 ? t(`admin.noticeType.${camel(type)}`) : type.replace(/_/g, " ");
}
/** Relative time ("5m ago") in the active language; falls back to `date()` after 30 days. */
export function timeAgoLabel(t: T, date: (d: string | number | Date) => string, iso: string | Date): string {
  const d = typeof iso === "string" ? new Date(iso) : iso;
  const m = Math.round((Date.now() - d.getTime()) / 60000);
  if (m < 1) return t("admin.ago.now");
  if (m < 60) return t("admin.ago.minutes", { n: m });
  const h = Math.round(m / 60);
  if (h < 24) return t("admin.ago.hours", { n: h });
  const days = Math.round(h / 24);
  if (days < 30) return t("admin.ago.days", { n: days });
  return date(d);
}
/** Picks the `_one` variant of a plural pair when n === 1. */
export function plural(t: T, key: string, n: number): string {
  return n === 1 ? t(`${key}_one`, { n }) : t(key, { n });
}
